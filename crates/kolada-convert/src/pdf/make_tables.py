"""Writes tables.rs: the data the PDF reader needs, from pdfminer's copies
of Adobe's lists and from Python's Unicode database. Run with a Python that
has pdfminer.six installed:

    python make_tables.py
"""
import os
import unicodedata

from pdfminer.glyphlist import glyphname2unicode
from pdfminer.latin_enc import ENCODING

here = os.path.dirname(os.path.abspath(__file__))

# Glyph names, for the scripts and symbols documents use (uniXXXX names
# are read by their number instead).
RANGES = [(0x20, 0x24F), (0x2B0, 0x2FF), (0x370, 0x3FF), (0x400, 0x4FF), (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F),
          (0x2190, 0x21FF), (0x2200, 0x22FF), (0x25A0, 0x25FF), (0x2600, 0x26FF), (0x2700, 0x27BF), (0xFB00, 0xFB06)]
glyphs = sorted((n, u) for n, u in glyphname2unicode.items()
                if len(u) == 1 and not n.startswith('uni') and any(a <= ord(u) <= b for a, b in RANGES))


def rust_char(c):
    return "'\\u{%x}'" % ord(c)


def rust_str(s):
    return '"' + ''.join('\\u{%x}' % ord(c) for c in s) + '"'


# The four Latin encodings, code -> character.
tables = {k: ['\0'] * 256 for k in ('std', 'mac', 'win', 'pdf')}
for name, std, mac, win, pdf in ENCODING:
    u = glyphname2unicode.get(name)
    if not u or len(u) != 1:
        continue
    for key, code in (('std', std), ('mac', mac), ('win', win), ('pdf', pdf)):
        if code is not None:
            tables[key][code] = u
# WinAnsi as Windows has it: a bullet for unused codes in the high half is
# not text; space and the rest as written.
for c in range(0x20, 0x7F):
    if tables['win'][c] == '\0':
        tables['win'][c] = chr(c)

# Arabic presentation forms -> the letters they show.
arabic = []
for cp in list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFF00)):
    d = unicodedata.decomposition(chr(cp))
    if d.startswith('<'):
        letters = ''.join(chr(int(h, 16)) for h in d.split()[1:])
        arabic.append((cp, letters))

with open(os.path.join(here, 'tables.rs'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('//! Generated by make_tables.py: glyph names, Latin encodings and Arabic\n'
            '//! presentation forms. Do not edit by hand.\n\n')
    f.write('/// Adobe glyph names (those for Latin, Greek, Cyrillic, punctuation and\n/// symbols), sorted by name.\n')
    f.write('pub static GLYPHS: &[(&str, char)] = &[\n')
    for n, u in glyphs:
        f.write('    ("%s", %s),\n' % (n, rust_char(u)))
    f.write('];\n\n')
    for key, doc in (('std', 'StandardEncoding'), ('mac', 'MacRomanEncoding'), ('win', 'WinAnsiEncoding'), ('pdf', 'PDFDocEncoding')):
        f.write('/// %s, by code; NUL where a code has no character.\n' % doc)
        f.write('pub static %s: [char; 256] = [\n' % key.upper())
        for row in range(0, 256, 16):
            f.write('    ' + ', '.join(rust_char(c) for c in tables[key][row:row + 16]) + ',\n')
        f.write('];\n\n')
    f.write('/// Arabic presentation forms (U+FB50 to U+FEFF) and the letters they are.\n')
    f.write('pub static ARABIC: &[(u16, &str)] = &[\n')
    for cp, letters in arabic:
        f.write('    (0x%04X, %s),\n' % (cp, rust_str(letters)))
    f.write('];\n')
print('glyphs', len(glyphs), 'arabic', len(arabic))
